"""Обработчик специализированного Python-агента."""

from typing import Protocol

from router.registry import Agent
from router.task import Task


class ChatClient(Protocol):
    """Интерфейс клиента модели, необходимый обработчику."""

    def chat(self, prompt: str) -> str:
        """Получить текстовый ответ на запрос."""
        ...


PYTHON_AGENT_INSTRUCTIONS = """
Ты — специализированный Python-агент проекта AI Product Lab.

Твоя задача — помогать пользователю разрабатывать и понимать Python-код.

Правила работы:
1. Отвечай на русском языке, если пользователь не попросил другой язык.
2. Объясняй решения понятно начинающему разработчику.
3. При исправлении предоставленного файла выдавай полный исправленный код.
4. Если данных недостаточно, задай конкретные уточняющие вопросы.
5. Не придумывай содержимое файлов, результаты выполнения или тестирования.
6. Отделяй обнаруженные ошибки от предположений.
7. Предлагай проверки, которые помогают убедиться в правильности решения.
8. Учитывай указанную пользователем версию Python и операционную систему.
9. Перед изменением существующих файлов напоминай о резервной копии.

В этом режиме у тебя есть только возможность подготовить текстовый ответ.
У тебя нет инструментов для выполнения кода, изменения файлов,
установки пакетов или управления компьютером.
Не утверждай, что выполнил такие действия.
""".strip()


class PythonAgentHandler:
    """Подготовить запрос по Python и вернуть ответ предоставленного клиента."""

    def __init__(self, client: ChatClient) -> None:
        self.client = client

    def __call__(self, task: Task, agent: Agent) -> str:
        """Обработать задачу по контракту TaskExecutor."""
        prompt = (
            PYTHON_AGENT_INSTRUCTIONS
            + "\n\nЗАДАЧА ПОЛЬЗОВАТЕЛЯ:\n"
            + task.description
        )

        return self.client.chat(prompt)